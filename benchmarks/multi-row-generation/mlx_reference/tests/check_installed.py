"""Build-independent wheel/checkpoint compatibility test, launched outside the repository.

Run with the training environment's Python and explicit --wheel, --checkpoints,
--compiler-binary, and --report paths. No experiment module is imported in the
installed consumer process. The reference is generated by a separate subprocess.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import zipfile

import mlx.core as mx
import numpy as np

HERE = Path(__file__).resolve()
ROOT = HERE.parents[2]
CROSSRUN = ROOT / 'benchmarks/multi-row-generation/crossrun'
NAMES = [f'{arm}-{seed}' for arm in ('learned', 'static', 'aux') for seed in (1703, 1709)]
MASKS = ('none', 'parents', 'parents_latent')


def tables():
    a = np.array([[[3,1],[3,1],[5,0],[7,3]], [[0,0],[1,0],[2,3],[3,3]]], np.int32)
    b = np.array([[[3,2],[3,0],[5,1],[1,2]], [[2,0],[0,0],[0,1],[3,1]]], np.int32)
    req = np.array([[[0,1,0],[1,0,1],[2,2,3],[3,3,2]], [[0,1,0],[2,0,1],[0,2,1],[3,3,3]]], np.int32)
    return a, b, req


def output_record(raw, stages, pairs):
    out = {'pairs': np.array(pairs)}
    for step, (head, decoded) in enumerate(zip(raw, stages)):
        for index, value in enumerate(head):
            out[f'run{step}-logits{index}'] = np.array(value)
        for name, value in decoded.items():
            out[f'run{step}-{name}'] = np.array(value)
    return out


def reference(args):
    sys.path.insert(0, str(CROSSRUN))
    from cross_model import CrossRun, decode, projection_recipe
    mx.set_default_device(mx.gpu)
    inputs = [mx.array(a) for a in tables()]
    plan = projection_recipe(CROSSRUN / 'compiler/plan.json')
    for name in NAMES:
        model = CrossRun(name.split('-')[0], plan)
        model.load_weights(str(args.checkpoints / name / 'model.safetensors'))
        for mask in MASKS:
            raw, pairs = model(*inputs, mask=mask)
            np.savez(f'{name}-{mask}.npz', **output_record(raw, decode(raw), pairs))


def installed(args):
    site = Path.cwd() / 'installation'
    sys.path.insert(0, str(site))
    import eggfuse
    assert Path(eggfuse.__file__).resolve().is_relative_to(site)
    assert not any(Path(p).resolve().is_relative_to(ROOT) for p in sys.path)
    compiled = eggfuse.compile_projection(Path('program.egg'), compiler_binary=args.compiler_binary,
                                          output_path='plan.json')
    assert compiled['schema'] == 'eggfuse.crossrun.direct-input-projection/v1'
    for name in NAMES:
        model = eggfuse.load_model(args.checkpoints / name, 'plan.json')
        for mask in MASKS:
            stages, pairs = eggfuse.infer(model, *tables(), mask=mask)
            raw, _ = model(*[mx.array(t) for t in tables()], mask=mask)
            measured = output_record(raw, stages, pairs)
            with np.load(f'{name}-{mask}.npz') as original:
                for key, arr in measured.items():
                    expected = original[key]
                    assert arr.shape == expected.shape and arr.dtype == expected.dtype
                    np.testing.assert_array_equal(arr.view(np.uint8), expected.view(np.uint8),
                                                  err_msg=f'{name}/{mask}/{key}')
    leaked = sorted(k for k in sys.modules if k in ('cross_model','network','crossrun_data','crossrun_audit','assignment','train'))
    assert not leaked, leaked
    report = dict(imported_from='temporary pip installation outside checkout',
                  compiler_sha256=hashlib.sha256(args.compiler_binary.read_bytes()).hexdigest(),
                  generated_plan_sha256=hashlib.sha256(Path('plan.json').read_bytes()).hexdigest(),
                  checkpoints=NAMES, masks=MASKS, graphs_per_case=2, stage_logits_bit_exact=True,
                  discrete_outputs_bit_exact=True, generated_90_float_pair_tokens_bit_exact=True,
                  experiment_modules_imported=leaked)
    args.report.write_text(json.dumps(report, indent=2)+'\n')


def main():
    parser = argparse.ArgumentParser()
    for key in ('wheel', 'checkpoints', 'compiler-binary', 'report'):
        parser.add_argument('--'+key, type=lambda p: Path(p).resolve(), required=True)
    parser.add_argument('--phase', choices=('reference','installed'))
    args = parser.parse_args()
    if args.phase == 'reference':
        reference(args)
        return
    if args.phase == 'installed':
        installed(args)
        return
    with zipfile.ZipFile(args.wheel) as wheel:
        names = wheel.namelist()
        assert all(name.startswith(('eggfuse/', 'eggfuse-0.1.0.dist-info/')) for name in names)
        assert not any(name.endswith(('.npz','.safetensors','.egg')) for name in names)
    common = [sys.executable, '-I', str(HERE), '--wheel', str(args.wheel), '--checkpoints', str(args.checkpoints),
              '--compiler-binary', str(args.compiler_binary), '--report', str(args.report)]
    with tempfile.TemporaryDirectory() as location:
        work = Path(location)
        assert not work.resolve().is_relative_to(ROOT)
        (work/'program.egg').write_text((CROSSRUN/'compiler/rules.egg').read_text() + '\n'
                                        '(A 0 3 1) (B 1 3 2) (Request 0 1 0)\n'
                                        '(run-schedule (seq (run make) (run finish)))\n')
        subprocess.run([sys.executable, '-m', 'pip', 'install', '--no-index','--no-deps','--no-compile',
                        '--target', str(work/'installation'), str(args.wheel)], cwd=work, check=True)
        for phase in ('reference','installed'):
            subprocess.run([*common,'--phase',phase], cwd=work, check=True)
    print(args.report.read_text())

if __name__ == '__main__':
    main()
